# ---------------------------------------------------------------- заготовки

def rect(x0, y0, x1, y1):
    return [[x0, y0], [x1, y0], [x1, y1], [x0, y1]]


def lens(v, p, m="head", res=0.035, h=0.014, rim=0.009, **kw):
    """Фара или фонарь: стекло в выступающем тёмном корпусе."""
    return dict(v=v, m=m, p=p, res=res, rim=[rim, "trim", h], **kw)


def disc(v, x, y, r, m="head", h=0.012, rim=0.008, rim_m="trim", **kw):
    """Круглая линза (прожектор, фонарь, кольцо)."""
    return dict(v=v, c=[x, y, r], m=m, res=0.025, rim=[rim, rim_m, h], **kw)


def projector(v, x, y, r=0.028):
    """Линза-прожектор внутри фары: хромовое кольцо и светящийся центр."""
    return [dict(v=v, c=[x, y, r], m="chrome", res=0.02, lift=0.022, detail=True),
            dict(v=v, c=[x, y, r * 0.62], m="head", res=0.02, lift=0.026, detail=True)]


def intake(v, p, m="grille", rim_m="trim", w=0.014, h=0.024, res=0.06, bars=None, **kw):
    """Воздухозаборник: сетка в глубоком ободке (внутренняя стенка тёмная)."""
    d = dict(v=v, m=m, p=p, res=res, rim=[w, rim_m, h], **kw)
    if bars:
        d["bars"] = bars
    return d


def plate(v, y, h=0.11, w=0.52, lift=0.016):
    """Номерной знак в тёмной рамке."""
    return dict(v=v, m="plate", sym=False, res=0.4, lift=lift, p=rect(-w / 2, y, w / 2, y + h), rim=[0.012, "trim", 0.006])


def badge(v, x, y, r=0.035, m="chrome", sx=1.0, **kw):
    return dict(v=v, c=[x, y, r, sx], m=m, sym=False, res=0.03, lift=0.02, raise_=0.006, detail=True, **kw)


def handle(t, y, length=0.025, m="chrome"):
    """Дверная ручка: приподнятая планка на боковине (t — вдоль машины)."""
    return dict(v="side", m=m, res=0.02, raise_=0.01, detail=True, p=rect(t - length, y - 0.012, t, y + 0.012))


def third_brake(t0, t1):
    """Третий стоп-сигнал вверху заднего стекла."""
    return dict(v="surf", m="tail", res=0.05, lift=0.01, p=rect(t0, 10.2, t1, 11.0))


def spine(t0, t1, w, h, m="paint", x=0.0):
    """Хребет / ребро сверху вдоль машины (вид сверху: x, t)."""
    return dict(v="top", m=m, sym=x > 0.0, res=0.06, raise_=h,
                p=[[x - w / 2, t0], [x + w / 2, t0], [x + w / 2, t1], [x - w / 2, t1]])


def blade(p, h=0.02, m="paint", **kw):
    """Лезвие на боковине (вид сбоку: t, y), приподнятое над кузовом."""
    return dict(v="side", m=m, p=p, res=0.04, raise_=h, **kw)


def star(cx, cy, r):
    pts = []
    for i in range(6):
        a = math.pi / 2 + i * math.pi / 3
        rr = r if i % 2 == 0 else r * 0.2
        pts.append([round(cx + math.cos(a) * rr, 4), round(cy + math.sin(a) * rr, 4)])
    return pts


def merge(key, **over):
    b = json.loads(json.dumps(CURVES[key]))
    b.update(over)
    return b


