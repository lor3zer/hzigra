# Станция: (z — метры от носа, низ, нижняя кромка боковины x, макс. ширина x, её высота,
#           плечо x, y, линия окон / край капота x, y, край крыши / середина капота x, y, центр верха y)
# Из этих чисел строятся 9 опорных точек сечения c1..c9 (см. st()).

def st(z, yb, bot, mx, ymx, sh, ysh, belt, ybelt, re, yre, yc, sill=None, low=None):
    c1 = (bot, yb)
    c2 = sill or (bot + (mx - bot) * 0.7, yb + min(0.08, (ymx - yb) * 0.35))
    c3 = low or (mx * 0.995, yb + (ymx - yb) * 0.6)
    c4 = (mx, ymx)
    c5 = (sh, ysh)
    c6 = (belt, ybelt)
    c7 = (re, yre)
    c8 = (re * 0.5, yre + (yc - yre) * 0.85)
    c9 = (0.0, yc)
    return (z, yb, [c1, c2, c3, c4, c5, c6, c7, c8, c9])


