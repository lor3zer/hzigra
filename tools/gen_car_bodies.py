def main():
    out = [HEADER]
    for key, b in B.items():
        out.append("\t# ------------------------------------------------ " + b["_title"])
        out.append('\t"%s": {' % key)
        line = []
        for k, v in b.items():
            if k.startswith("_"):
                continue
            if k in ("decals", "parts"):
                if line:
                    out.append("\t\t" + ", ".join(line) + ",")
                    line = []
                out.append('\t\t"%s": [' % k)
                for d in v:
                    out.append("\t\t\t" + (d if isinstance(d, str) else gd(d) + ","))
                out.append("\t\t],")
                continue
            item = '"%s": %s' % (k, gd(v))
            if line and len(", ".join(line + [item])) > 110:
                out.append("\t\t" + ", ".join(line) + ",")
                line = []
            line.append(item)
        if line:
            out.append("\t\t" + ", ".join(line) + ",")
        out.append("\t},")
        out.append("")
    out.append("}")
    out.append("")
    out.append("")
    out.append("static func get_body(id: String) -> Dictionary:")
