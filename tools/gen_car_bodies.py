# старые номера панелей сечения -> промежутки опорных точек нового каркаса
_SPAN = {3: 1, 4: 2, 5: 3, 6: 4, 7: 5, 8: 6, 9: 7, 10: 8}
_DROP = ["w", "tuck", "lo", "zh", "sh", "top", "roof", "ghw", "ght", "scallop", "handles"]


def apply_geom():
    for key, g in GEOM.items():
        b = B[key]
        L = g["L"]
        for k in _DROP:
            b.pop(k, None)
        net = []
        for z, yb, pts in g["stations"]:
            row = [round(z / L, 4), yb]
            for x, y in pts:
                row += [x, y]
            net.append(row)
        b["net"] = net
        b["crease"] = g["crease"]
        for k in ("ws", "side", "rear"):
            b[k] = [round(v / L, 4) for v in g[k]]
        b["pillars"] = [[round(p[0] / L, 4), round(p[1] / L, 4)] for p in g["pillars"]]
        if "deck" in g:
            b["deck"] = [[round(d[0] / L, 4), round(d[1] / L, 4), d[2]] for d in g["deck"]]
        else:
            b.pop("deck", None)
        b["seams"] = [[sm[0], _SPAN.get(sm[1], 1), _SPAN.get(sm[2], 8)] for sm in b.get("seams", [])]
        b["hlines"] = [[h[0], h[1], _SPAN.get(h[2], 6), h[3]] for h in b.get("hlines", [])]
        if "fuel" in b:
            b["fuel"] = [b["fuel"][0], _SPAN.get(b["fuel"][1], 4)]
        # окна и молдинги вдоль сечения: новая нумерация опорных точек
        dy = g.get("rear_dy", 0.0)
        for d in b["decals"]:
            if isinstance(d, dict) and d.get("v") == "surf":
                d["p"] = [[q[0], round(q[1] - 2.0, 4)] for q in d["p"]]
            # корма стала ниже: фонари и решётки опускаем вместе с ней
            if isinstance(d, dict) and d.get("v") == "rear" and dy != 0.0:
                if "p" in d:
                    d["p"] = [[q[0], round(q[1] + dy, 4)] for q in d["p"]]
                if "c" in d:
                    d["c"] = [d["c"][0], round(d["c"][1] + dy, 4)] + d["c"][2:]
        for e in b.get("exhaust", []):
            e["y"] = round(e["y"] + dy * (0.5 if e["y"] > 0.5 else 0.0), 4)


# ---------------------------------------------------------------- вывод в GDScript

def gd(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        r = round(v, 4)
        return repr(r)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "[" + ", ".join(gd(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join('"%s": %s' % (k.rstrip("_"), gd(x)) for k, x in v.items()) + "}"
    raise TypeError(v)


